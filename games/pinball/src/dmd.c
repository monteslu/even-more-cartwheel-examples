void dmd_clear(dmd *d) { memset(d->dot, 0, sizeof d->dot); }

void dmd_set(dmd *d, int x, int y, int v) {
  if (x < 0 || y < 0 || x >= DMD_W || y >= DMD_H) return;
  if (v > 15) v = 15;
  if (v > d->dot[y][x]) d->dot[y][x] = (uint8_t)v;
}

static const uint8_t *glyph(char c) {
  if (c >= 'a' && c <= 'z') c = (char)(c - 32);
  if (c < 32 || c > 90) c = ' ';
  return FONT[c - 32];
}

int dmd_text_width(const char *s, int scale) {
  int n = (int)strlen(s);
  return n ? n * 6 * scale - scale : 0;
}

void dmd_text(dmd *d, const char *s, int x, int y, int scale, int v) {
  for (; *s; s++, x += 6 * scale) {
    const uint8_t *g = glyph(*s);
    for (int cx = 0; cx < 5; cx++)
      for (int cy = 0; cy < 7; cy++)
        if (g[cx] >> cy & 1)
          for (int sy = 0; sy < scale; sy++)
            for (int sx = 0; sx < scale; sx++) dmd_set(d, x + cx * scale + sx, y + cy * scale + sy, v);
  }
}

void dmd_text_c(dmd *d, const char *s, int cx, int y, int scale, int v) { dmd_text(d, s, cx - dmd_text_width(s, scale) / 2, y, scale, v); }

void dmd_rect(dmd *d, int x, int y, int w, int h, int v) {
  for (int j = y; j < y + h; j++)
    for (int i = x; i < x + w; i++) dmd_set(d, i, j, v);
}

void dmd_render(const dmd *d, uint8_t *rgba, const float col[3]) {
  /* each dot a soft round spot in a DMD_S x DMD_S cell; unlit dots a faint glow of the panel's colour */
  static float mask[DMD_S][DMD_S];
  static bool made;
  if (!made) {
    for (int y = 0; y < DMD_S; y++)
      for (int x = 0; x < DMD_S; x++) {
        float dx = (float)x + 0.5f - DMD_S * 0.5f, dy = (float)y + 0.5f - DMD_S * 0.5f, r = sqrtf(dx * dx + dy * dy) / (DMD_S * 0.5f);
        mask[y][x] = r < 0.62f ? 1.0f : r < 0.92f ? (0.92f - r) / 0.3f : 0;
      }
    made = true;
  }
  float cr = col[0], cg = col[1], cb = col[2];
  for (int y = 0; y < DMD_H; y++)
    for (int x = 0; x < DMD_W; x++) {
      float v = (float)d->dot[y][x] / 15.0f, lit = 0.06f + 0.94f * v;
      for (int sy = 0; sy < DMD_S; sy++) {
        uint8_t *p = rgba + (((size_t)(y * DMD_S + sy) * DMD_W * DMD_S) + (size_t)x * DMD_S) * 4;
        for (int sx = 0; sx < DMD_S; sx++, p += 4) {
          float m = mask[sy][sx] * lit;
          float hot = v > 0.8f ? (v - 0.8f) * 2.5f * mask[sy][sx] : 0; /* the brightest dots burn toward white */
          p[0] = (uint8_t)fminf(255, (cr * m + hot * 0.35f) * 255);
          p[1] = (uint8_t)fminf(255, (cg * m + hot * 0.3f) * 255);
          p[2] = (uint8_t)fminf(255, (cb * m + hot * 0.25f) * 255);
          p[3] = 255;
        }
      }
    }
}
