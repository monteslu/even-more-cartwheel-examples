// Writes assets/grade/contrast.cube: the game's colour grade, contrast curves on each display channel (after the
// tonemap). Two S curves one after the other: values a tenth brighter, then (x/0.35)^1.5 below 0.35 and the mirror of
// it above; then the same around 0.55 with a power of 1.8. Black stays black and white stays white. Each setting
// takes its own share of the grade (GRADE in src/view.c, the node's grade_intensity).
//   node games/destructo/tools/gen-grade.mjs
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SIZE = 33;
const s = (pivot, power, gain) => (v) => {
  const x = Math.min(1, v * gain);
  return x < pivot ? pivot * Math.pow(x / pivot, power) : 1 - (1 - pivot) * Math.pow((1 - x) / (1 - pivot), power);
};
const first = s(0.35, 1.5, 1.1), second = s(0.55, 1.8, 1.0);
const curve = (v) => second(first(v));

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'assets', 'grade', 'contrast.cube');
const lines = ['# destructo contrast grade (generated by tools/gen-grade.mjs)', 'TITLE "contrast"', `LUT_3D_SIZE ${SIZE}`,
  'DOMAIN_MIN 0 0 0', 'DOMAIN_MAX 1 1 1'];
for (let b = 0; b < SIZE; b++)
  for (let g = 0; g < SIZE; g++)
    for (let r = 0; r < SIZE; r++)
      lines.push([r, g, b].map((i) => curve(i / (SIZE - 1)).toFixed(6)).join(' '));
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join('\n') + '\n');
console.log(`wrote ${out}`);
