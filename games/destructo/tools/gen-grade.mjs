// Writes assets/grade/contrast.cube: the game's colour grade, applied to the display values after the tonemap. Two S curves
// per channel (values a tenth brighter, then a hard S round 0.35 and another round 0.55: clean contrast, deep but not crushed
// darks, which also pushes colour apart), then more saturation, the shadows pulled toward a cool blue and the highlights toward
// warm gold (a warm sun, a cool sky in the shade). Black stays black and white stays white. Each setting takes its own share of
// the grade (GRADE in src/view.c, the node's grade_intensity).
//   node games/destructo/tools/gen-grade.mjs
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SIZE = 33;
const s = (pivot, power, gain) => (v) => {
  const x = Math.min(1, v * gain);
  return x < pivot ? pivot * Math.pow(x / pivot, power) : 1 - (1 - pivot) * Math.pow((1 - x) / (1 - pivot), power);
};
const first = s(0.35, 1.5, 1.1), second = s(0.55, 1.8, 1.0);
const curve = (v) => second(first(v));
const sat = 1.22;
const SHADOW = [-0.02, 0.0, 0.05], HIGH = [0.035, 0.012, -0.04];
const grade = (rgb) => {
  const l = 0.2126 * rgb[0] + 0.7152 * rgb[1] + 0.0722 * rgb[2];
  const ws = Math.pow(1 - l, 2.2) * (1 - 0.4 * l), wh = Math.pow(l, 2.0);
  return rgb.map((v, i) => {
    let c = l + (v - l) * sat;
    c = curve(Math.min(1, Math.max(0, c)));
    c += SHADOW[i] * ws * (c < 0.02 ? c / 0.02 : 1) + HIGH[i] * wh * (1 - c < 0.02 ? (1 - c) / 0.02 : 1);
    return Math.min(1, Math.max(0, c));
  });
};

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'assets', 'grade', 'contrast.cube');
const lines = ['# destructo colour grade (generated by tools/gen-grade.mjs)', 'TITLE "contrast"', `LUT_3D_SIZE ${SIZE}`,
  'DOMAIN_MIN 0 0 0', 'DOMAIN_MAX 1 1 1'];
for (let b = 0; b < SIZE; b++)
  for (let g = 0; g < SIZE; g++)
    for (let r = 0; r < SIZE; r++)
      lines.push(grade([r, g, b].map((i) => i / (SIZE - 1))).map((v) => v.toFixed(6)).join(' '));
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join('\n') + '\n');
console.log(`wrote ${out}`);
