SPACING = 5.0

def decor_file(name, builders):
    """eight props, one a frame: each is built at its own spot along x (the occlusion bake sees it alone), each frame
    brings the shown one to the origin and folds the rest to a point on the floor"""
    K = Kit(len(builders)); M = K.M
    for k, fn in enumerate(builders):
        off = Vector((SPACING * (k + 1), 0, 0))
        nm = "p%d" % k
        with K.part(nm):
            v0 = len(M.v)
            fn(M)
            for i in range(v0, len(M.v)):
                p = M.v[i]
                M.v[i] = Vector((p.x, p.y, max(p.z, 0.0))) + off      # nothing below the floor
    # a hidden speck of glow so every decor file has a group 1
    if not any(g == 1 for g in M.grp):
        with K.part("speck"):
            mesh(M, "root", [(0, 0, 0.0), (0.001, 0, 0.0), (0, 0.001, 0.0)], [(0, 1, 2)], WHITE, group=1, noise_amt=0)
    per = []
    for k in range(len(builders)):
        a, b = K.parts["p%d" % k][0]
        per.append(sum(len(f) - 2 for f in M.faces if a <= f[0] < b))
    print("TOWERS %s tris per prop %s" % (name, per))
    for f in range(len(builders)):
        for k in range(len(builders)):
            off = Vector((SPACING * (k + 1), 0, 0))
            K.set(f, "p%d" % k, Matrix.Translation(-off) if k == f else FOLD((0, 0, 0)))
    return finish_t(name, K)

def tree(M, h, cr, dark, light, seed, trunk=(0.42, 0.29, 0.18), blobs=4, squash=0.8):
    """a broadleaf tree: a stout trunk under a crown of lumps (a high centre one and blobs round it), each lump lit
    from its own top and the whole crown darker at its rim, so from straight above it reads as a rounded mass"""
    rng = random.Random(seed)
    zc = h - cr * squash * 1.25
    M.limb("root", (0, 0, 0), (0.0, 0.0, zc), 0.2, 0.12, trunk, seg=6)
    for j in range(3):
        a = TAU * j / 3 + seed
        M.limb("root", (0, 0, 0.05), (0.36 * math.cos(a), 0.36 * math.sin(a), -0.02), 0.12, 0.04, colvar(trunk, 0.9), seg=3)
    lumps = [((0.0, 0.0, zc + cr * 0.22), cr * 0.66, (9, 5))]
    for j in range(blobs):
        a = TAU * j / blobs + rng.random() * 0.5 + seed
        rr = cr * (0.5 + 0.06 * rng.random())
        d = cr * 0.5
        lumps.append(((d * math.cos(a), d * math.sin(a), zc - cr * 0.12 + rng.random() * cr * 0.12), rr, (6, 4)))
    for (c, rr, seg) in lumps:
        v0 = len(M.v)
        M.ell("root", c, (rr, rr, rr * squash), light, seg=seg, noise_amt=0)
        for i in range(v0, len(M.v)):
            p = M.v[i]
            q = p - Vector(c)
            p = p + q.normalized() * noise.noise(p * 2.6 + Vector((seed, 0, 0))) * 0.07 * cr
            M.v[i] = p
            tl = max(0.0, min(1.0, (p.z - (c[2] - rr * squash)) / (2 * rr * squash)))      # the lump's own light
            tg = max(0.0, min(1.0, (p.z - (zc - cr * 0.6)) / (cr * 1.5)))                   # the crown's
            rim = max(0.0, math.hypot(p.x, p.y) / cr - 0.55)
            t = max(0.0, 0.55 * tl ** 1.2 + 0.45 * tg - 0.35 * rim)
            M.col[i] = colvar(mix(dark, light, t), 1.0 + 0.07 * noise.noise(p * 3.3))

