def palm(M, seed):
    rng = random.Random(seed)
    pts = [Vector((0, 0, 0)), Vector((0.06, 0.02, 1.0)), Vector((0.15, 0.05, 2.0)), Vector((0.28, 0.08, 3.0))]
    for s in range(3):
        M.limb("root", tuple(pts[s]), tuple(pts[s + 1] + Vector((0, 0, 0.05))), 0.16 - 0.03 * s, 0.14 - 0.03 * s, colvar((0.6, 0.45, 0.28), 1 + 0.08 * s), seg=6)
    top = pts[3]
    v0 = len(M.v)
    for j in range(7):
        a = TAU * j / 7 + rng.random() * 0.3
        d = Vector((math.cos(a), math.sin(a), 0))
        # a frond: a flattened leaf arching out and down, kept inside the 2 m footprint
        L = 0.8
        mid = top + d * L * 0.55 + Vector((0, 0, 0.18))
        end = top + d * L + Vector((0, 0, -0.35))
        for (p0, p1, w0, w1) in ((top, mid, 0.06, 0.22), (mid, end, 0.22, 0.03)):
            dd = p1 - p0
            side = dd.cross(Vector((0, 0, 1))).normalized()
            V = [p0 - side * w0, p0 + side * w0, p1 + side * w1, p1 - side * w1]
            V = [tuple(v) for v in V]
            mesh(M, "root", V, [(0, 1, 2, 3)], (0.3, 0.62, 0.22), noise_amt=0.05)        # one sided: the camera is always above
    grade(M, v0, len(M.v), (0.16, 0.38, 0.12), (0.48, 0.78, 0.28))
    for j in range(3):
        a = TAU * j / 3
        M.ell("root", tuple(top + Vector((0.1 * math.cos(a), 0.1 * math.sin(a), -0.1))), (0.08, 0.08, 0.09), (0.45, 0.3, 0.15), seg=(6, 4))

