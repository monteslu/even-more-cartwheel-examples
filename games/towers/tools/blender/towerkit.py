def beam_base():
    K = Kit(3); M = K.M
    base_core(K, 6, math.pi / 6, BEAMD, BEAMB, (0.46, 0.38, 0.6), GOLD,
              colprof=[(0.0, 0.17), (0.46, 0.17), (0.44, 0.32), (0.36, 1.2), (0.42, 1.36), (0.0, 1.38)])
    # glowing strips down the six column edges (level 1 on)
    for j in range(6):
        a = j * TAU / 6 + math.pi / 6
        with K.part("strip%d" % j):
            M.limb("root", (0.0, 0, 0.36), (0.0, 0, 1.18), 0.03, 0.03, WHITE, group=1, seg=4, noise_amt=0)
        # follow the column's taper: built on the axis, moved out to the edge per height
        for (s, e) in K.parts["strip%d" % j]:
            for i in range(s, e):
                p = M.v[i]
                rr = 0.44 + (0.36 - 0.44) * (p.z - 0.32) / (1.2 - 0.32) + 0.0
                p2 = Vector((p.x + rr * 0.97, p.y, p.z))
                M.v[i] = Matrix.Rotation(a, 4, 'Z') @ p2
        show_from(K, "strip%d" % j, 0, mats=[along(l, 0.17) @ TS((0, 0, 0.17), s=(1, 1, (TOP[l] - 0.29) / 1.21)) for l in range(3)])
    # buttress fins (level 2): three blades from the column to the plinth edge, magenta edged
    for j in range(3):
        a = j * TAU / 3 + math.pi / 2
        with K.part("fin%d" % j):
            prism(M, "root", [(0.3, 0.0), (0.8, 0.0), (0.8, 0.28), (0.36, 0.95)], -0.06, 0.06, BEAMD, c=(0, 0, 0), rot=(math.pi / 2, 0, 0), bevel=0.015)
