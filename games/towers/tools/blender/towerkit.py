MUZZLE = {}

def head_disc(K, col, trim=TRIM, r=0.4, seg=12):
    M = K.M
    with K.part("disc"):
        lathe(M, "root", [(0.0, 0.0), (r, 0.0), (r, 0.08), (r - 0.06, 0.12), (0.0, 0.12)], col, seg=seg, noise_amt=0.06)
    with K.part("disc_trim"):
        ring(M, (0, 0, 0.07), r - 0.02, r + 0.05, 0.035, trim, group=2, seg=seg)

def grow(K, scales, keep=("disc", "disc_trim"), about=(0, 0, 0.0)):
    """every part not in keep and not already set is scaled per level about the pivot base"""
    for l in range(3):
        G = TS(about, s=scales[l])
        for nm in K.parts:
            if nm in keep: continue
            if nm in K.frames[l]:
                K.frames[l][nm] = G @ K.frames[l][nm]
            else:
                K.frames[l][nm] = G
    return [TS(about, s=scales[l]) for l in range(3)]

def muzzle(kind, K, pts, G):
    """pts: the rest muzzle (Blender axes) per level, before the level's growth; written in game axes"""
    out = []
    for l in range(3):
        p = G[l] @ Vector(pts[l])
        out.append([round(p.x, 4), round(p.z, 4), round(-p.y, 4)])
    MUZZLE[kind] = out

