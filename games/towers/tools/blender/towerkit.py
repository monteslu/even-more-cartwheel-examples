# Towers' models, headless:
#   flatpak run --filesystem=home org.blender.Blender --background --factory-startup --python \
#     <abs>/games/towers/tools/blender/towerkit.py -- <abs out dir> [name ...]
# names: see KIT at the end (default all). Writing any head also rewrites towers.json (the muzzle points).
#
# Every model is a .cwchar (format in cwchar_lib.py / crawler's hordechars.py): group 0 lit with vertex colours
# (colours above 1.5 are HDR emissive), group 1 an unlit glow the game multiplies by a per-instance colour (authored
# white or grey: the grey is the intensity), group 2 a team trim drawn lit and multiplied by the owner's colour.
# Game axes: metres, y up; here Blender's z is up and the game's +Z (south, toward the camera) is Blender's -Y.
# One topology per file: a file's frames are the same vertices moved. A tower's levels carry every part and fold
# the parts a level does not have to a hidden point; a decor file carries all eight props and folds the seven not
# shown to a point on the floor.
# The camera looks almost straight down from far away (about 25 px a metre), so every shape here is chunky, its
# identity on the top faces and the glow. Every shape is generated by this script (no outside art).
