# ───────────────────────── parts and frames ───────────────────────────

class Kit:
    """A Model whose vertices are grouped into named parts; frames are {part: Matrix} applied to the rest pose."""
    def __init__(self, nframes):
        self.M = Model()
        self.M.bone("root", None, (0, 0, 0), (0, 0, 1))
        self.parts = {}
        self.frames = [dict() for _ in range(nframes)]
        self.post = [None] * nframes            # optional fn(pos) run on a frame's positions after the matrices

    @contextmanager
    def part(self, name):
        v0 = len(self.M.v)
        yield
        self.parts.setdefault(name, []).append((v0, len(self.M.v)))

    def verts(self, name):
        for (a, b) in self.parts[name]:
            for i in range(a, b): yield i

    def set(self, f, name, mat):
        self.frames[f][name] = mat

    def fold(self, f, name, pt):
        self.frames[f][name] = FOLD(pt)

def FOLD(pt):
    return Matrix.Translation(Vector(pt)) @ Matrix.Diagonal((TINY, TINY, TINY, 1.0))

def TS(c0, c1=None, s=1.0, rot=None):
    """moves the point c0 to c1, scaling (uniform or per axis) and rotating (a Matrix 3x3) about it"""
    c0 = Vector(c0); c1 = Vector(c1) if c1 is not None else c0
    if isinstance(s, (int, float)): s = (s, s, s)
    S = Matrix.Diagonal((s[0], s[1], s[2], 1.0))
    R = rot.to_4x4() if rot is not None else Matrix.Identity(4)
    return Matrix.Translation(c1) @ R @ S @ Matrix.Translation(-c0)

def orient(d):
    return tuple(Vector((0, 0, 1)).rotation_difference(Vector(d).normalized()).to_euler())

def finish_t(name, K, grounded=True, ao_samples=40, ao_deep=None, report=None):
    """builds the mesh, bakes occlusion at rest (the glow keeps its value), poses every frame from the part
    matrices, grounds it if it stands on the floor, writes the file and prints the bounds of each frame in game axes"""
    M = K.M
    bpy.ops.wm.read_factory_settings(use_empty=True)
    ob, arm = build_object(M, name)
    pose_frame_s(arm, {})
    ao = bake_ao(ob, M, ao_samples, *(ao_deep or ()))
    for fi, f in enumerate(M.faces):
        if M.grp[fi] == 1:
            for i in f: ao[i] = 1.0
    ob.modifiers.clear()
    me = ob.data
    rest = [v.co.copy() for v in me.vertices]
    clip = []
    for fi, fr in enumerate(K.frames):
        pos = [p.copy() for p in rest]
        for nm, mat in fr.items():
            for i in K.verts(nm): pos[i] = mat @ rest[i]
        if K.post[fi]: K.post[fi](pos)
        for k, v in enumerate(me.vertices): v.co = pos[k]
        me.update()
        clip.append(([v.co.copy() for v in me.vertices], [tuple(n.vector) for n in me.corner_normals], [l.vertex_index for l in me.loops]))
    for k, v in enumerate(me.vertices): v.co = rest[k]
    me.update()
    if grounded:
        ground(clip)
    size = write_cwchar(os.path.join(OUT, name + ".cwchar"), M, ao, [clip], ob)
    tris = [0] * (max(M.grp) + 1)
    for p in me.polygons:
        tris[p.material_index] += len(p.vertices) - 2
    print("TOWERS %s: %d verts, tris %s (total %d), frames %d, %d bytes" % (name, len(M.v), tris, sum(tris), len(clip), size))
    for fi, (pos, _, _) in enumerate(clip):
        xs = [p.x for p in pos]; ys = [p.z for p in pos]; zs = [-p.y for p in pos]
        rxz = max(math.hypot(p.x, p.y) for p in pos)
        print("TOWERS   %s f%d  x[%.3f %.3f] y[%.3f %.3f] z[%.3f %.3f] rxz %.3f" % (name, fi, min(xs), max(xs), min(ys), max(ys), min(zs), max(zs), rxz))
    return tris

# ───────────────────────── shape helpers ──────────────────────────────

def torus(M, c, R, r, color, seg=16, rs=6, group=0, rot=(0, 0, 0), sx=1.0, sy=1.0, noise_amt=0.05):
    prof = [(R + r * math.cos(TAU * k / rs), r * math.sin(TAU * k / rs)) for k in range(rs)]
    prof.append(prof[0])
    lathe(M, "root", prof, color, seg=seg, group=group, c=c, rot=rot, sx=sx, sy=sy, cap_top=False, cap_bot=False, noise_amt=noise_amt)

def ring(M, c, r_in, r_out, t, color, group=0, seg=16, rot=(0, 0, 0)):
    lathe(M, "root", [(r_in, -t), (r_out, -t), (r_out, t), (r_in, t), (r_in, -t)], color, group=group, seg=seg, c=c, rot=rot, cap_top=False, cap_bot=False, noise_amt=0.03)

LIGHT = Vector((-0.45, -0.55, 0.7)).normalized()

def gem(M, base, d, w, L, col, group=0, seg=6, shoulder=0.68, foot=0.8, spin=0.0, lo=0.62, sink=0.3):
    """a crystal: a prism of seg sides from base along d, pointed at L; a glow one gets a grey per facet (lit from
    the upper left) so it reads as a faceted solid though it is drawn unlit"""
    d = Vector(d).normalized()
    R = Vector((0, 0, 1)).rotation_difference(d).to_matrix()
    base = Vector(base)
    A = [spin + TAU * k / seg for k in range(seg)]
    r0 = [base + R @ Vector((w * foot * math.cos(a), w * foot * math.sin(a), 0)) for a in A]
    r1 = [base + R @ Vector((w * math.cos(a), w * math.sin(a), L * shoulder)) for a in A]
    tip = base + R @ Vector((0, 0, L)); bot = base + R @ Vector((0, 0, -w * sink))
    facets = []
    for k in range(seg):
        k2 = (k + 1) % seg
        facets += [(r0[k], r0[k2], r1[k2], r1[k]), (r1[k], r1[k2], tip), (r0[k2], r0[k], bot)]
    if group == 1:
        for f in facets:
            n = (f[1] - f[0]).cross(f[2] - f[1])
            n = n.normalized() if n.length > 1e-9 else Vector((0, 0, 1))
            s = lo + (1 - lo) * max(0.0, n.dot(LIGHT))
            mesh(M, "root", [tuple(p) for p in f], [tuple(range(len(f)))], colvar(col, s), group=1, noise_amt=0)
    else:
        V = []; F = []
        for f in facets:
            F.append(tuple(range(len(V), len(V) + len(f)))); V += [tuple(p) for p in f]
        mesh(M, "root", V, F, col, group=0, noise_amt=0.06)

def rock(M, c, r, col, seed, seg=(8, 5), amp=0.22, moss=None, moss_t=0.4, top=None):
    """a lumpy faceted rock, its bottom cut flat on the floor; moss (or snow) on the faces turned up"""
    v0 = len(M.v)
    M.ell("root", c, r, col, seg=seg, smooth=False, noise_amt=0.12)
    c = Vector(c); rm = (r[0] + r[1] + r[2]) / 3
    for i in range(v0, len(M.v)):
        p = M.v[i]
        dd = p - c
        n = noise.noise(p * 1.6 + Vector((seed * 3.1, seed * 1.7, seed * 0.3)))
        p = p + dd.normalized() * n * amp * rm
        p.z = max(p.z, 0.0)
        M.v[i] = p
        if moss is not None and dd.normalized().z > moss_t:
            k = min(1.0, (dd.normalized().z - moss_t) * 3.0)
            M.col[i] = mix(M.col[i], colvar(moss, 0.9 + 0.2 * noise.noise(p * 4.0)), k)

def grade(M, v0, v1, dark, light, z0=None, z1=None, nz=0.08, radial=0.0, cx=0.0, cy=0.0, R=1.0):
    """recolours vertices v0..v1 dark at the bottom to light at the top (a canopy's light-to-dark); radial darkens
    the outer rim a little too (from straight above, a lit dome)"""
    zs = [M.v[i].z for i in range(v0, v1)]
    z0 = min(zs) if z0 is None else z0; z1 = max(zs) if z1 is None else z1
    for i in range(v0, v1):
        p = M.v[i]
        t = max(0.0, min(1.0, (p.z - z0) / max(1e-6, z1 - z0)))
        t = t ** 0.85
        rr = math.hypot(p.x - cx, p.y - cy) / R
        t = max(0.0, t - radial * max(0.0, rr - 0.5))
        k = 1.0 + nz * noise.noise(p * 3.3)
        M.col[i] = colvar(mix(dark, light, t), k)

def blade_tuft(M, c, n, h, col, seed, spread=0.2, lean=0.35, r=0.05):
    rng = random.Random(seed)
    c = Vector(c)
    for k in range(n):
        a = TAU * k / n + rng.random() * 0.6
        b = c + Vector((math.cos(a) * spread * rng.random(), math.sin(a) * spread * rng.random(), 0))
        tip = b + Vector((math.cos(a) * lean * h, math.sin(a) * lean * h, h * (0.7 + 0.5 * rng.random())))
        M.limb("root", tuple(b), tuple(tip), r, r * 0.05, colvar(col, 0.85 + 0.3 * rng.random()), seg=3, noise_amt=0.05)

# ───────────────────────── tower bases ────────────────────────────────

def base_core(K, seg, rot, plinth, tier, column, collar, colprof=None, tier_from=1):
    """the shared shape: a plinth (team ring on its rim), a second tier from level tier_from+1, a column scaled to the
    level's height and a collar whose flat top is the mount, exactly at TOP[level] (the team band round it)"""
    M = K.M
    R = (0, 0, rot)
    with K.part("plinth"):
        lathe(M, "root", dense([(0.0, 0.0), (0.84, 0.0), (0.84, 0.12), (0.79, 0.17), (0.0, 0.17)]), plinth, seg=seg, rot=R, noise_amt=0.08, smooth=False)
    with K.part("plinth_trim"):
        ring(M, (0, 0, 0.175), 0.67, 0.78, 0.012, TRIM, group=2, seg=seg, rot=R)
    with K.part("tier"):
        lathe(M, "root", dense([(0.0, 0.12), (0.66, 0.12), (0.66, 0.27), (0.61, 0.31), (0.0, 0.31)]), tier, seg=seg, rot=R, noise_amt=0.08, smooth=False)
    with K.part("column"):
        prof = colprof or [(0.0, 0.17), (0.47, 0.17), (0.45, 0.3), (0.39, 1.38), (0.0, 1.38)]
        lathe(M, "root", dense(prof), column, seg=seg, rot=R, noise_amt=0.08, smooth=False)
    with K.part("collar"):
        lathe(M, "root", [(0.0, 1.36), (0.44, 1.36), (0.5, 1.4), (0.5, 1.46), (0.46, 1.5), (0.0, 1.5)], collar, seg=seg, rot=R, noise_amt=0.05, smooth=False)
    for l in range(3):
        k = (TOP[l] - 0.12 - 0.17) / (1.38 - 0.17)
        K.set(l, "column", TS((0, 0, 0.17), s=(1, 1, k)))
        K.set(l, "collar", Matrix.Translation((0, 0, TOP[l] - 1.5)))
    for l in range(tier_from):
        K.fold(l, "tier", (0, 0, 0.05))

def dense(prof, step=0.14):
    """a lathe profile with extra rings along its long spans (the occlusion bake is per vertex)"""
    out = [prof[0]]
    for (a, b) in zip(prof, prof[1:]):
        L = math.hypot(b[0] - a[0], b[1] - a[1])
        n = int(L / step) if a[0] > 1e-6 and b[0] > 1e-6 else 0
        for k in range(1, n + 1):
            t = k / (n + 1)
            out.append((a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t))
        out.append(b)
    return out

def along(l, z):
    """the translation that keeps a point at height z on the column where the level's scaled column puts it"""
    k = (TOP[l] - 0.12 - 0.17) / (1.38 - 0.17)
    return Matrix.Translation((0, 0, (z - 0.17) * (k - 1)))

def show_from(K, name, L, pt=(0, 0, 0.05), mats=None):
    """part shown from level L (0-based); mats: optional per level matrices for the levels it shows"""
    for l in range(3):
        if l < L: K.fold(l, name, pt)
        elif mats: K.set(l, name, mats[l])

def bolt_base():
    K = Kit(3); M = K.M
    base_core(K, 8, math.pi / 8, SLATE_D, SLATE, (0.52, 0.55, 0.64), COPPER_D)
    with K.part("floorglow"):
        ring(M, (0, 0, 0.315), 0.49, 0.6, 0.008, WHITE, group=1, seg=8, rot=(0, 0, math.pi / 8))
    show_from(K, "floorglow", 2)
    # copper coil bands round the column: one, two, three
    for j, z in enumerate((0.55, 0.85, 1.15)):
        with K.part("band%d" % j):
            torus(M, (0, 0, z), 0.44 - 0.05 * (z - 0.17), 0.06, COPPER, seg=16, rs=6)
        show_from(K, "band%d" % j, j, mats=[along(l, z) for l in range(3)])
    # insulator pylons on the corners (level 2 short, level 3 tall with copper braces to the column)
    for j in range(4):
        a = math.pi / 4 + j * math.pi / 2
        x, y = 0.56 * math.cos(a), 0.56 * math.sin(a)
        with K.part("pylon%d" % j):
            M.limb("root", (x, y, 0.3), (x, y, 1.02), 0.075, 0.06, STEEL_D, seg=6)
            for z in (0.5, 0.68, 0.86):
                lathe(M, "root", [(0.0, z - 0.03), (0.12, z - 0.02), (0.12, z + 0.0), (0.0, z + 0.02)], COPPER, seg=8, c=(x, y, 0), noise_amt=0.04)
            lathe(M, "root", [(0.0, 1.0), (0.09, 1.01), (0.09, 1.04), (0.0, 1.06)], COPPER_D, seg=8, c=(x, y, 0))
        with K.part("pylon_orb%d" % j):
            M.ell("root", (x, y, 1.12), (0.1, 0.1, 0.1), WHITE, group=1, seg=(8, 5), noise_amt=0)
        with K.part("brace%d" % j):
            M.limb("root", (x * 0.92, y * 0.92, 0.95), (x * 0.55, y * 0.55, 1.22), 0.035, 0.035, COPPER, seg=5)
        lv2 = TS((x, y, 0.3), s=(0.85, 0.85, 0.62))
        show_from(K, "pylon%d" % j, 1, mats=[None, lv2, Matrix.Identity(4)])
        orb2 = TS((x, y, 1.12), (x, y, 0.3 + (1.12 - 0.3) * 0.62), 0.75)
        show_from(K, "pylon_orb%d" % j, 1, mats=[None, orb2, Matrix.Identity(4)])
        show_from(K, "brace%d" % j, 2)
    # glowing conduits up the column faces (level 3)
    for j in range(4):
        a = j * math.pi / 2
        with K.part("conduit%d" % j):
            cuboid(M, "root", (-0.035, -0.02, 0.35), (0.035, 0.02, 1.3), WHITE, group=1, noise_amt=0, faces="xXyYZ")
        for i in K.verts("conduit%d" % j):          # lie on the tapered column face
            p = M.v[i]
            M.v[i] = Vector((p.x + (0.45 - 0.06 * (p.z - 0.3) / 1.08) * 0.93, p.y, p.z))
        rot_off(K, "conduit%d" % j, a, 0.0)
        show_from(K, "conduit%d" % j, 2)
    return finish_t("tower_bolt_base", K)

def rot_off(K, name, a, r):
    """turns a part built on the +x side about z to angle a, at radius r"""
    M = K.M
    R = Matrix.Rotation(a, 4, 'Z') @ Matrix.Translation((r, 0, 0))
    for (s, e) in K.parts[name]:
        for i in range(s, e): M.v[i] = R @ M.v[i]

