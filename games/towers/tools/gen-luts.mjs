// towers' colour grades: a 3D LUT (.cube) per theme, the hordeshooter recipe (an S-curve, a tint split between
// shadows and highlights, saturation, a lift under the blacks) with each theme's own numbers: colourful, with real
// contrast, never crushed toward dark. All generated here.
//   node tools/gen-luts.mjs [out dir (default assets/grade)]
import { writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const GRADES = { // more contrast than a gentle curve, blacks kept deep (a hair of lift), saturation held level: the
  // palettes carry the colour (mapbuild.c), the grade carries the punch
  meadow: { contrast: 1.0, shadow: [-0.02, 0.0, 0.04], high: [0.04, 0.025, -0.03], sat: 0.85, lift: [0.0, 0.0, 0.004] },
  autumn: { contrast: 1.0, shadow: [-0.02, -0.005, 0.05], high: [0.05, 0.02, -0.04], sat: 0.76, lift: [0.0, 0.0, 0.004] },
  desert: { contrast: 0.85, shadow: [-0.03, 0.0, 0.05], high: [0.04, 0.02, -0.04], sat: 0.88, lift: [0.0, 0.0, 0.004] },
  snow: { contrast: 0.6, shadow: [-0.01, 0.01, 0.05], high: [0.03, 0.015, -0.03], sat: 1.3, lift: [0.0, 0.0, 0.006] },
  volcano: { contrast: 0.6, shadow: [0.01, -0.01, 0.05], high: [0.05, 0.02, -0.04], sat: 0.88, lift: [0.004, 0.0, 0.006] },
  crystal: { contrast: 0.6, shadow: [0.0, -0.01, 0.04], high: [0.03, 0.03, -0.03], sat: 0.88, lift: [0.002, 0.0, 0.006] },
};
const out = resolve(process.argv[2] || join(dirname(fileURLToPath(import.meta.url)), '../assets/grade'));
const N = 17;
const sc = (x) => { const y = Math.min(1, Math.max(0, x)); return y * y * (3 - 2 * y); };
const clamp = (x) => Math.min(1, Math.max(0, x));
mkdirSync(out, { recursive: true });
for (const [name, g] of Object.entries(GRADES)) {
  const lines = [`# towers ${name} grade (generated by tools/gen-luts.mjs)`, `TITLE "${name}"`, `LUT_3D_SIZE ${N}`, 'DOMAIN_MIN 0 0 0', 'DOMAIN_MAX 1 1 1'];
  for (let b = 0; b < N; b++) for (let gg = 0; gg < N; gg++) for (let r = 0; r < N; r++) {
    let c = [r / (N - 1), gg / (N - 1), b / (N - 1)];
    c = c.map((x) => x + (sc(x) - x) * g.contrast);
    const L = 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
    const sh = Math.pow(1 - L, 2), hi = L * L;
    c = c.map((x, i) => x + g.shadow[i] * sh + g.high[i] * hi);
    const L2 = 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
    c = c.map((x) => L2 + (x - L2) * g.sat);
    c = c.map((x, i) => g.lift[i] + x * (1 - g.lift[i]));
    lines.push(c.map((x) => clamp(x).toFixed(5)).join(' '));
  }
  writeFileSync(join(out, `${name}.cube`), lines.join('\n') + '\n');
}
console.log(`gen-luts: ${Object.keys(GRADES).length} grades into ${out}`);
